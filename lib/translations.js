// Helper getter function
export function getTranslation(key, lang = 'en') {
  if (TRANSLATIONS[key]) {
    return TRANSLATIONS[key][lang] || TRANSLATIONS[key].en;
  }
  return key;
}

// Generate localized TEXT dictionary for components
export function getDictionary(lang = 'en') {
  const dict = {};
  for (const [k, v] of Object.entries(TRANSLATIONS)) {
    dict[k] = v[lang] || v.en;
  }
  return dict;
}
